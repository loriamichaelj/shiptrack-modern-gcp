CREATE ROLE shiptrack_app LOGIN PASSWORD 'app-test-only';
CREATE SCHEMA shiptrack;
CREATE TABLE shiptrack.carriers (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(8) NOT NULL UNIQUE,
  name varchar(100) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE shiptrack.shipments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tracking_number varchar(12) NOT NULL UNIQUE,
  carrier_id smallint NOT NULL REFERENCES shiptrack.carriers (id),
  origin varchar(100) NOT NULL,
  destination varchar(100) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'CREATED',
  promised_delivery_at timestamptz NOT NULL,
  estimated_delivery_at timestamptz,
  delivered_at timestamptz,
  last_event_at timestamptz,
  sla_breached boolean NOT NULL DEFAULT false,
  sla_breached_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_shipments_status CHECK (status IN
    ('CREATED', 'PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED', 'EXCEPTION'))
);
CREATE TABLE shiptrack.tracking_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id uuid NOT NULL REFERENCES shiptrack.shipments (id),
  event_type varchar(20) NOT NULL,
  location varchar(100) NOT NULL,
  occurred_at timestamptz NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  idempotency_key varchar(64) NOT NULL UNIQUE,
  applied boolean NOT NULL,
  payload jsonb,
  CONSTRAINT ck_tracking_events_type CHECK (event_type IN
    ('PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED', 'EXCEPTION'))
);
CREATE TABLE shiptrack.pod_documents (
  id uuid PRIMARY KEY,
  shipment_id uuid NOT NULL REFERENCES shiptrack.shipments (id),
  storage_uri text NOT NULL,
  content_type varchar(50) NOT NULL,
  size_bytes bigint NOT NULL,
  sha256 char(64) NOT NULL,
  uploaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE shiptrack.sla_alerts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id uuid NOT NULL REFERENCES shiptrack.shipments (id),
  detected_at timestamptz NOT NULL DEFAULT now(),
  detected_by varchar(64) NOT NULL
);
